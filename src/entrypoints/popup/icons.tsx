import type { ReactNode } from 'react';

// A line icon, sized and colored like the text around it.
function Icon({
  className = '',
  children,
}: {
  className?: string;
  children: ReactNode;
}) {
  return (
    <svg
      viewBox="0 0 24 24"
      className={`size-4 ${className}`}
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
    >
      {children}
    </svg>
  );
}

// The back arrow, or the arrow into a section.
export function Chevron({
  direction,
  className,
}: {
  direction: 'left' | 'right';
  className?: string;
}) {
  return (
    <Icon className={className}>
      <path d={direction === 'left' ? 'M15 18l-6-6 6-6' : 'M9 18l6-6-6-6'} />
    </Icon>
  );
}

